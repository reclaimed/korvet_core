// ---------------------------------------------------------------------------
// kbd_map.hpp — таблица соответствия «латинская клавиша → позиция в матрице
// клавиатуры Корвета» для ввода текста в minigui.
//
// Раскладка КАЛИБРОВАНА ЭМПИРИЧЕСКИ по ПЗУ 2.0 (загрузка Бейсика, ввод
// каждой клавиши, чтение эха с экрана): строки 0-5 основного поля
// совпадают с таблицами документации, КРОМЕ линии KB05 — фактическая
// раскладка ПЗУ: 8 9 : ; , - . / (в таблицах документации указано
// 8 9 * + < = > /). Русские буквы не транслитерируются — для кириллицы
// переключайте АЛФ и используйте --key с координатами матрицы.
// ---------------------------------------------------------------------------

#include <cstdint>
#include <cstring>

namespace korvet {
namespace minigui {

struct KeyCoord {
    uint8_t row;
    uint8_t col;
};

inline bool lookup_key(char c, KeyCoord& out) {
    // Латиница и цифры (основное поле) — по калибровке ПЗУ 2.0:
    //   строка = бит возврата (0..7), столбец = линия (KB00..KB07).
    static const struct { char ch; uint8_t row, col; } table[] = {
        {'@', 0, 0}, {'A', 1, 0}, {'B', 2, 0}, {'C', 3, 0}, {'D', 4, 0},
        {'E', 5, 0}, {'F', 6, 0}, {'G', 7, 0},
        {'H', 0, 1}, {'I', 1, 1}, {'J', 2, 1}, {'K', 3, 1}, {'L', 4, 1},
        {'M', 5, 1}, {'N', 6, 1}, {'O', 7, 1},
        {'P', 0, 2}, {'Q', 1, 2}, {'R', 2, 2}, {'S', 3, 2}, {'T', 4, 2},
        {'U', 5, 2}, {'V', 6, 2}, {'W', 7, 2},
        {'X', 0, 3}, {'Y', 1, 3}, {'Z', 2, 3}, {'[', 3, 3}, {'\\', 4, 3},
        {']', 5, 3}, {'^', 6, 3}, {'_', 7, 3},
        {'0', 0, 4}, {'1', 1, 4}, {'2', 2, 4}, {'3', 3, 4}, {'4', 4, 4},
        {'5', 5, 4}, {'6', 6, 4}, {'7', 7, 4},
        // KB05 — фактическая раскладка ПЗУ 2.0 (калибровка):
        {'8', 0, 5}, {'9', 1, 5}, {':', 2, 5}, {';', 3, 5}, {',', 4, 5},
        {'-', 5, 5}, {'.', 6, 5}, {'/', 7, 5},
        // KB06: ⏎ CLS STOP DEL INS ⇦ TAB SPACE
        {'\n', 0, 6}, {'\t', 6, 6}, {' ', 7, 6},
    };
    for (const auto& e : table) {
        if (e.ch == c) {
            out.row = e.row;
            out.col = e.col;
            return true;
        }
    }
    return false;
}

/// Специальные клавиши по имени (row<<8|col).
inline bool lookup_named_key(const char* name, uint16_t& out) {
    static const struct { const char* name; uint8_t row, col; } table[] = {
        {"ENTER", 0, 6}, {"RETURN", 0, 6},
        {"CLS", 1, 6}, {"STOP", 2, 6}, {"DEL", 3, 6}, {"INS", 4, 6},
        {"LEFT", 5, 6}, {"TAB", 6, 6}, {"SPACE", 7, 6},
        {"LSH", 0, 7}, {"ALF", 1, 7}, {"GRF", 2, 7}, {"ESC", 3, 7},
        {"SEL", 4, 7}, {"CTRL", 5, 7}, {"FIX", 6, 7}, {"RSH", 7, 7},
        {"F1", 0, 10}, {"F2", 1, 10}, {"F3", 2, 10}, {"F4", 3, 10},
        {"F5", 4, 10}, {"F6", 5, 10}, {"F7", 6, 10}, {"F8", 7, 10},
        {"F9", 0, 11}, {"F10", 1, 11},
        {"PRT", 5, 12}, {"PCHT", 5, 12},  // ПЧТ — 13-я колонка (адрес 110H)
        {"SHIFT", 0, 7},
    };
    for (const auto& e : table) {
        if (strcmp(name, e.name) == 0) {
            out = static_cast<uint16_t>((e.row << 8) | e.col);
            return true;
        }
    }
    return false;
}

}  // namespace minigui
}  // namespace korvet
