#pragma once
#include <cstdint>
#include <cstddef>

namespace korvet {

// ---------------------------------------------------------------------------
// IFddImageAdapter — единственная точка доступа Fdc к содержимому дискет.
//
// korvet_core НЕ хранит образы дисков и не знает, откуда они берутся:
// файл на диске хоста, файл на SD-карте (FatFs, RP2040), сетевой ресурс —
// не важно. Ядро лишь просит конкретный сектор конкретного диска и получает
// либо отказ (диск не вставлен / сектор вне диапазона / ошибка чтения).
//
// side передаётся ОТДЕЛЬНО от track: в физическом формате КДИ (KDI)
// сторона — самостоятельный параметр позиционирования головки, а не часть
// номера дорожки (раскладка в смещение файла — дело конкретной реализации
// адаптера, см. пример в gui_qt5/media/qfile_fdd_adapter.h).
//
// Реализация на Windows/Linux (gui_qt5) может как читать сектор напрямую
// из QFile::seek()+QFile::read() на каждый вызов (без буферизации всего
// образа в RAM), так и кэшировать что-то у себя — это решение хоста.
// Реализация на RP2040 читает сектор прямо с SD-карты через FatFs.
// ---------------------------------------------------------------------------
class IFddImageAdapter {
public:
    virtual ~IFddImageAdapter() = default;

    // Вставлен ли физически диск в данный привод (0..3).
    virtual bool is_present(uint8_t drive) const = 0;

    // Защищена ли дискета от записи (влияет на будущую поддержку бита
    // write-protect в статусе ВГ93 — сейчас Fdc его не проверяет, см.
    // комментарий в fdc.cpp::disk_init(), но интерфейс уже готов).
    virtual bool is_write_protected(uint8_t drive) const = 0;

    // Прочитать/записать один сектор. buf_size всегда равен Fdc::SECTOR_SIZE
    // (1024) — параметр передаётся для явной защиты от переполнения на
    // стороне реализации адаптера.
    // Возвращает false при отсутствии диска, промахе по диапазону или
    // ошибке ввода-вывода — Fdc в этом случае сообщает контроллеру
    // ошибку операции (см. Exit::OP_CONTSUM в dsk_vg()).
    virtual bool read_sector(uint8_t drive, uint8_t track, uint8_t side,
                              uint8_t sector, uint8_t* buf, size_t buf_size) = 0;
    virtual bool write_sector(uint8_t drive, uint8_t track, uint8_t side,
                               uint8_t sector, const uint8_t* buf, size_t buf_size) = 0;
};

}  // namespace korvet
